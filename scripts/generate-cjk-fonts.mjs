// Builds src/app/fonts/noto-sc-cjk.css: the Noto Sans/Serif SC variable fonts restricted to Chinese
// characters and CJK punctuation, under their own family names. They sit in front of the Latin fonts in
// each stack, so Chinese uses Noto SC while letters and digits keep Pretendard / Tinos (Pretendard also
// carries some Hanja, which would otherwise mix Korean-style glyphs into Chinese text).
// Run: node scripts/generate-cjk-fonts.mjs
import { readFileSync, writeFileSync } from "node:fs";

const MIN = 0x2e80; // CJK radicals and up; nothing Latin, Greek, Cyrillic or general punctuation
const sources = [
  ["noto-sans-sc", "PGC Sans SC"],
  ["noto-serif-sc", "PGC Serif SC"],
];

const out = ["/* Generated by scripts/generate-cjk-fonts.mjs — do not edit by hand. */"];
for (const [pkg, family] of sources) {
  const css = readFileSync(`node_modules/@fontsource-variable/${pkg}/wght.css`, "utf8");
  for (const block of css.match(/@font-face\s*{[^}]*}/g)) {
    const file = block.match(/files\/([^)]+\.woff2)/)[1];
    const ranges = block.match(/unicode-range:\s*([^;]+);/)[1].split(",").map((r) => r.trim());
    const kept = [];
    for (const r of ranges) {
      const [a, b = a] = r.replace(/^U\+/i, "").split("-");
      let lo = parseInt(a, 16);
      const hi = parseInt(b, 16);
      if (hi < MIN) continue;
      lo = Math.max(lo, MIN);
      kept.push(lo === hi ? `U+${lo.toString(16)}` : `U+${lo.toString(16)}-${hi.toString(16)}`);
    }
    if (!kept.length) continue;
    out.push(
      `@font-face{font-family:"${family}";font-style:normal;font-display:swap;font-weight:100 900;` +
        `src:url("../../../node_modules/@fontsource-variable/${pkg}/files/${file}") format("woff2-variations");` +
        `unicode-range:${kept.join(",")}}`,
    );
  }
}
writeFileSync("src/app/fonts/noto-sc-cjk.css", out.join("\n") + "\n");
console.log(`wrote ${out.length - 1} @font-face rules`);
